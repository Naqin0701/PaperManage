package store

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"papermgr/internal/config"
	"papermgr/internal/model"
)

// BibEntry is a rendered BibTeX entry.
type BibEntry struct {
	Citekey string
	Type    string
	Fields  map[string]string
}

// ExportBib regenerates library.bib (FR-8).
func (s *Store) ExportBib() error {
	s.bibMu.Lock()
	defer s.bibMu.Unlock()
	content, err := s.BibContent()
	if err != nil {
		return err
	}
	return config.AtomicWrite(filepath.Join(s.Root, "library.bib"), []byte(content), 0o644)
}

// BibContent renders the whole library as BibTeX.
func (s *Store) BibContent() (string, error) {
	keys, err := s.AllCitekeys()
	if err != nil {
		return "", err
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "%% generated by papermgr at %s\n%% do not edit; regenerate with `papermgr bib export`\n\n",
		time.Now().Format(time.RFC3339))
	for _, ck := range keys {
		p, err := s.Load(ck)
		if err != nil {
			continue
		}
		e := renderBib(p.Meta)
		fmt.Fprintf(&b, "@%s{%s,\n", e.Type, e.Citekey)
		var names []string
		for name := range e.Fields {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			val := e.Fields[name]
			if val == "" {
				continue
			}
			fmt.Fprintf(&b, "  %s = {%s},\n", name, val)
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

func renderBib(m model.Meta) BibEntry {
	typ := m.EntryType
	if typ == "" {
		typ = "misc"
	}
	f := map[string]string{
		"title":         bibEscape(m.Title),
		"author":        bibAuthors(m.Authors),
		"year":          "",
		"abstract":      bibEscape(m.Abstract),
		"keywords":      strings.Join(m.Keywords, ", "),
		"doi":           m.DOI,
		"url":           m.URL,
		"language":      m.Language,
		"eprint":        m.ArxivID,
		"archiveprefix": "",
	}
	if m.Year != nil {
		f["year"] = fmt.Sprint(*m.Year)
	}
	if m.ArxivID != "" {
		f["archiveprefix"] = "arXiv"
	}
	if m.Venue != nil {
		kind := strings.ToLower(m.Venue.Kind)
		switch {
		case kind == "journal":
			f["journal"] = bibEscape(m.Venue.Name)
		case kind == "conference":
			f["booktitle"] = bibEscape(m.Venue.Name)
		case m.Venue.Name != "":
			f["booktitle"] = bibEscape(m.Venue.Name)
		}
		if m.Venue.Volume != nil {
			f["volume"] = *m.Venue.Volume
		}
		if m.Venue.Issue != nil {
			f["number"] = *m.Venue.Issue
		}
		if m.Venue.Pages != nil {
			f["pages"] = *m.Venue.Pages
		}
		if m.Venue.Publisher != nil {
			f["publisher"] = bibEscape(*m.Venue.Publisher)
		}
	}
	return BibEntry{Citekey: m.Citekey, Type: typ, Fields: f}
}

func bibAuthors(as []model.Author) string {
	var parts []string
	for _, a := range as {
		name := strings.TrimSpace(a.Family)
		if a.Given != "" {
			if name != "" {
				name = name + ", " + a.Given
			} else {
				name = a.Given
			}
		}
		if name != "" {
			parts = append(parts, name)
		}
	}
	return strings.Join(parts, " and ")
}

func bibEscape(s string) string {
	// Keep braces balanced enough for BibTeX while preserving LaTeX in titles.
	s = strings.ReplaceAll(s, "\\", `\textbackslash{}`)
	s = strings.ReplaceAll(s, "&", `\&`)
	s = strings.ReplaceAll(s, "%", `\%`)
	s = strings.ReplaceAll(s, "#", `\#`)
	return s
}

// WriteBibTo writes BibTeX to an arbitrary path (used by --dry-run tests).
func (s *Store) WriteBibTo(path string) error {
	content, err := s.BibContent()
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}
